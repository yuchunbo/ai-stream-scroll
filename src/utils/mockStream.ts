/**
 * 创建Mock流式输出实例
 * @param text 要输出的文本
 * @param config 输出配置
 * @param onChunk 每块内容回调
 * @param onComplete 完成回调
 * @param onPause 暂停回调
 * @param onResume 继续回调
 */
export function createMockStream(
  text: string,
  config: StreamConfig,
  onChunk: (chunk: string) => void,
  onComplete: () => void,
  onPause: () => void,
  onResume: () => void
) {
  let currentIndex = 0
  let isPaused = false
  let isStopped = false
  let timeoutId: ReturnType<typeof setTimeout> | null = null

  /**
   * 获取下一块内容
   */
  const getNextChunk = (): string => {
    if (currentIndex >= text.length) return ''

    switch (config.chunkSize) {
      case 'char':
        return text[currentIndex++]
      case 'word':
        const wordEnd = text.indexOf(' ', currentIndex)
        if (wordEnd === -1) {
          const chunk = text.slice(currentIndex)
          currentIndex = text.length
          return chunk
        }
        const chunk = text.slice(currentIndex, wordEnd + 1)
        currentIndex = wordEnd + 1
        return chunk
      case 'sentence':
        const sentenceEnd = text.indexOf('。', currentIndex)
        if (sentenceEnd === -1) {
          const chunk = text.slice(currentIndex)
          currentIndex = text.length
          return chunk
        }
        const sentenceChunk = text.slice(currentIndex, sentenceEnd + 1)
        currentIndex = sentenceEnd + 1
        return sentenceChunk
      default:
        return text[currentIndex++]
    }
  }

  /**
   * 获取延迟时间（带随机波动）
   */
  const getDelay = (): number => {
    const base = config.speed
    return Math.random() * base + base / 2
  }

  /**
   * 处理下一块内容
   */
  const processNextChunk = () => {
    if (isPaused || isStopped) return

    const chunk = getNextChunk()
    if (chunk) {
      onChunk(chunk)
      timeoutId = setTimeout(processNextChunk, getDelay())
    } else {
      onComplete()
    }
  }

  /**
   * 开始输出
   */
  const start = () => {
    isStopped = false
    isPaused = false
    processNextChunk()
  }

  /**
   * 暂停输出
   */
  const pause = () => {
    isPaused = true
    if (timeoutId) {
      clearTimeout(timeoutId)
      timeoutId = null
    }
    onPause()
  }

  /**
   * 继续输出
   */
  const resume = () => {
    isPaused = false
    processNextChunk()
    onResume()
  }

  /**
   * 停止输出
   */
  const stop = () => {
    isStopped = true
    isPaused = false
    if (timeoutId) {
      clearTimeout(timeoutId)
      timeoutId = null
    }
  }

  /**
   * 重置输出
   */
  const reset = () => {
    stop()
    currentIndex = 0
  }

  /**
   * 获取进度百分比
   */
  const getProgress = (): number => {
    return (currentIndex / text.length) * 100
  }

  return {
    start,
    pause,
    resume,
    stop,
    reset,
    getProgress,
    getState: (): StreamState => ({
      isRunning: !isPaused && !isStopped && currentIndex < text.length,
      isPaused,
      progress: getProgress(),
      currentIndex
    })
  }
}
